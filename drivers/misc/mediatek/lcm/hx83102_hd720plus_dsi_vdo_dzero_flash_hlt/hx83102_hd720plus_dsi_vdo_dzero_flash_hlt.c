static void lcm_init_power(void)
{

	display_bias_enable();
}


static void lcm_init(void)
{
	int size;

    SET_RESET_PIN(1);
    MDELAY(10);
 
	SET_RESET_PIN(0);
	MDELAY(10);

	SET_RESET_PIN(1);
	MDELAY(60);

	if (lcm_dsi_mode == CMD_MODE) {
		size = sizeof(init_setting_cmd) /
			sizeof(struct LCM_setting_table);
		push_table(NULL, init_setting_cmd, size, 1);
	} else {
		size = sizeof(init_setting_vdo) /
			sizeof(struct LCM_setting_table);
		push_table(NULL, init_setting_vdo, size, 1);
	}
}

static void lcm_suspend(void)
{
	push_table(NULL, lcm_suspend_setting,
		sizeof(lcm_suspend_setting) / sizeof(struct LCM_setting_table),1);

	MDELAY(10);

	printk("himax hlt d-zero flash  lcm_suspend double_tap_himax_work_flags = %d\r\n",double_tap_himax_work_flags);

		
	if (double_tap_himax_work_flags == 0)
	{

        double_tap_himax_work_flags_resume = 0;
		display_bias_disable();
	}
	else
    {
	   double_tap_himax_work_flags_resume = 1;
	}


}

static void lcm_resume(void)
{



	printk("himax hlt d-zero flash  lcm_resume double_tap_himax_work_flags = %d\r\n",double_tap_himax_work_flags);


   if (double_tap_himax_work_flags_resume == 0)
	{
		display_bias_enable();
	}
  
	MDELAY(15);
	push_table(NULL, init_setting_vdo,
		sizeof(init_setting_vdo) / sizeof(struct LCM_setting_table),1);
	MDELAY(10);


}

